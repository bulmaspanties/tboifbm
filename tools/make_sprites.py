def referee_flag():
    g = blank()
    # yellow cloth with a soft fold, weighted knot top-left
    for y in range(9, 25):
        wave = 1 if 13 <= y <= 18 else 0
        rect(g, 9 + wave, y, 24 - wave, y, "Y")
    for y in range(9, 25):
        for x in range(9, 25):
            if g[y][x] == "Y" and (x - 9) + (24 - y) < 6:
                g[y][x] = "y"
    put(g, [(x, x + 2) for x in range(12, 22) if g[x + 2][x] == "Y"], "y")   # fold line
    ellipse(g, 9, 8, 3, 3, "n")                      # weighted knot
    put(g, [(8, 7)], "N")
    return rows_of(outline(g))

def chin_strap():
    g = blank()
    # strap arcing under a chin cup, with snaps at both ends
    for x in range(4, 28):
        t = (x - 15.5) / 11.5
        y = int(round(11 + 9 * (1 - t * t)))
        rect(g, x, y, x, y + 1, "W")
        g[y + 1][x] = "w"
    ellipse(g, 15.5, 21, 6, 4, "W")                  # chin cup
    ellipse(g, 15.5, 22, 4.5, 2.5, "w")
    rect(g, 11, 18, 20, 18, "v")
    for cx in (5, 26):                               # snaps
        ellipse(g, cx, 11, 2.2, 2.2, "G")
        put(g, [(cx, 11)], "g")
    return rows_of(outline(g))


